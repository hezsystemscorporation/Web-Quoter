function detectLang() {
  let l = '';
  try { l = (typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage()) ||
             (typeof navigator !== 'undefined' && navigator.language) || 'en'; }
  catch { l = 'en'; }
  const s = String(l).toLowerCase();
  if (s.indexOf('zh') === 0) return /tw|hk|mo/.test(s) ? 'zh-TW' : 'zh-CN';
  if (s.indexOf('ko') === 0) return 'ko';
  if (s.indexOf('ja') === 0) return 'ja';
  if (s.indexOf('fr') === 0) return 'fr';
  return 'en';
}

function tr(lang, key) {
  const d = I18N[lang] || I18N.en;
  return d[key] !== undefined ? d[key] : I18N.en[key];
}
